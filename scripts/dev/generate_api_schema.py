#!/usr/bin/env python3
"""Regenerate the API wire-type registry, including standalone API families."""
import argparse
from pathlib import Path
import re
import subprocess
root=Path(__file__).resolve().parents[2]
names=set()
for source in sorted((root/'internal/daemon').glob('*.go')):
    if source.name.endswith('_test.go'): continue
    names.update(re.findall(r'^type ((?:V1|Metadata)\w+) (?:struct|=)',source.read_text(),re.M))
entries={name:name+'{}' for name in names}
entries['V1HealthResponse']='V1HealthResponse("")'
entries.update({name:'execapi.'+name+'{}' for name in ['ExecRequest','ExecResponse','ExecDryRunResponse','ExecErrorResponse','SSEEvent']})
entries.update({name:name+'{}' for name in ['PruneResult','PruneOutcome','schemaResponse']})
text='// Code generated by scripts/dev/generate_api_schema.py; DO NOT EDIT.\npackage daemon\n\nimport execapi "github.com/agentlab/agentlab/internal/api"\n\nvar schemaTypes = map[string]any{\n'
text+=''.join('"'+name+'": '+value+',\n' for name,value in sorted(entries.items()))+'}\n'
formatted=subprocess.run(['gofmt'],input=text,text=True,stdout=subprocess.PIPE,check=True).stdout
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
path=root/'internal/daemon/json_schema_types.go'
if args.check:
    if not path.exists() or path.read_text()!=formatted: raise SystemExit('API schema registry is out of date; run python3 scripts/dev/generate_api_schema.py')
else: path.write_text(formatted)
