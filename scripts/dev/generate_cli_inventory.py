#!/usr/bin/env python3
"""Append command definitions to CLI reference and refresh the llms inventory."""
import json,argparse
from pathlib import Path
root=Path(__file__).resolve().parents[2]
parser=argparse.ArgumentParser()
parser.add_argument("--reference",type=Path,default=root/"docs/reference/cli.md")
parser.add_argument("--llms-output",type=Path,default=root/"llms.txt")
args=parser.parse_args()
commands=json.loads((root/'internal/clicontract/commands.json').read_text())
def operands(command):
 count=command['operands']
 return ' [+modifier ...]' if count<0 else ''.join(f' <argument{i+1}>' for i in range(count))
def cell(value):return str(value).replace('|','\\|').replace('\n',' ')
reference=args.reference
text=reference.read_text()
text+='\n## Command catalog\n\nGenerated from the registered command definitions. `agentlab help <command>`\nshows the same command flags. Common flags accept values before or after operands.\nSaved preferences apply after explicit flags and existing environment overrides.\n\n'
for name,command in sorted(commands.items()):
 text+=f'### `{name}`\n\n```text\nagentlab {name}{operands(command)} [flags]\n```\n\n'
 flags=command['flags'];details=command.get('flag_details',{})
 if flags:
  text+='| Flag | Type | Default | Description |\n| --- | --- | --- | --- |\n'
  for flag,kind in sorted(flags.items()):
   detail=details.get(flag,{})
   text+=f'| `--{flag}` | {kind} | {cell(detail.get("default",""))} | {cell(detail.get("description",""))} |\n'
  text+='\n'
 text+=f'Help example: `agentlab help {name}`.\n\n'
reference.write_text(text.rstrip()+'\n')
llms=root/'llms.txt';text=llms.read_text()
start=text.index('### Full Command Tree');end=text.index('\n## Global Flags',start)
text=text[:start]+'### Full Command Tree\n\nGenerated by `make docs-gen` from registered CLI definitions.\n\n```text\n'+''.join('agentlab '+name+operands(command)+'\n' for name,command in sorted(commands.items()))+'```\n'+text[end:]
args.llms_output.write_text(text)
